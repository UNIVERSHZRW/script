-- Vinculación verificada de creadores e historial privado de donaciones Coins.
CREATE TABLE IF NOT EXISTS private.uhz_coin_creator_assignments(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 resource_id uuid NOT NULL REFERENCES public.content_resources(id),
 old_creator_id uuid REFERENCES auth.users(id),
 new_creator_id uuid NOT NULL REFERENCES auth.users(id),
 admin_id uuid NOT NULL REFERENCES auth.users(id),
 evidence_note text NOT NULL CHECK(char_length(evidence_note) BETWEEN 30 AND 2000),
 request_id uuid NOT NULL UNIQUE,
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE private.uhz_coin_creator_assignments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON private.uhz_coin_creator_assignments FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.uhz_coin_admin_assign_creator(
 p_resource_id uuid,p_creator_user_id uuid,p_evidence_note text,p_request_id uuid
) RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path TO ''
AS $function$
DECLARE actor uuid:=private.community_check_member(); old_author uuid; row_id bigint;
BEGIN
 IF actor IS NULL OR NOT private.uhz_license_admin() THEN RAISE EXCEPTION 'Solo administración' USING errcode='42501'; END IF;
 IF p_resource_id IS NULL OR p_creator_user_id IS NULL OR p_request_id IS NULL OR
    char_length(trim(coalesce(p_evidence_note,''))) NOT BETWEEN 30 AND 2000 THEN
   RAISE EXCEPTION 'Indica la publicación, el creador y la prueba de autoría' USING errcode='22023';
 END IF;
 SELECT id INTO row_id FROM private.uhz_coin_creator_assignments WHERE request_id=p_request_id;
 IF row_id IS NOT NULL THEN RETURN jsonb_build_object('ok',true,'already_processed',true,'audit_id',row_id); END IF;
 IF NOT EXISTS (SELECT 1 FROM auth.users u JOIN public.community_profiles p ON p.user_id=u.id
 WHERE u.id=p_creator_user_id AND u.email_confirmed_at IS NOT NULL AND u.deleted_at IS NULL) THEN
   RAISE EXCEPTION 'El creador debe tener un perfil verificado' USING errcode='22023';
 END IF;
 SELECT creator_user_id INTO old_author FROM public.content_resources
 WHERE id=p_resource_id AND publish AND record_status='ACTIVO' AND review_status ILIKE 'Verificado%'
 FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Publicación no elegible' USING errcode='22023'; END IF;
 IF EXISTS(SELECT 1 FROM private.uhz_coin_tips
   WHERE resource_kind='resource' AND resource_id=p_resource_id AND recipient_kind='creator'
     AND recipient_user_id<>p_creator_user_id) THEN
   RAISE EXCEPTION 'La publicación tiene propinas a otro autor; requiere revisión especializada' USING errcode='22023';
 END IF;
 IF old_author IS NOT DISTINCT FROM p_creator_user_id THEN
   RETURN jsonb_build_object('ok',true,'already_linked',true);
 END IF;
 UPDATE public.content_resources SET creator_user_id=p_creator_user_id WHERE id=p_resource_id;
 INSERT INTO private.uhz_coin_creator_assignments
 (resource_id,old_creator_id,new_creator_id,admin_id,evidence_note,request_id)
 VALUES(p_resource_id,old_author,p_creator_user_id,actor,trim(p_evidence_note),p_request_id)
 RETURNING id INTO row_id;
 RETURN jsonb_build_object('ok',true,'resource_id',p_resource_id,'linked',true,'audit_id',row_id);
END $function$;
REVOKE ALL ON FUNCTION public.uhz_coin_admin_assign_creator(uuid,uuid,text,uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.uhz_coin_admin_assign_creator(uuid,uuid,text,uuid) TO authenticated;

CREATE OR REPLACE FUNCTION public.uhz_coin_tip_my_history(p_limit integer DEFAULT 25)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO ''
AS $function$
DECLARE actor uuid:=private.community_check_member(); sent jsonb; received jsonb;
BEGIN
 IF actor IS NULL THEN RAISE EXCEPTION 'Inicia sesión' USING errcode='42501'; END IF;
 IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 100 THEN
   RAISE EXCEPTION 'Límite no válido' USING errcode='22023';
 END IF;
 SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.created_at DESC),'[]'::jsonb) INTO sent
 FROM (SELECT x.id,x.amount_coins,x.resource_kind,x.resource_id,x.recipient_kind,x.created_at,
       coalesce(p.display_name,'Creador') AS recipient
       FROM private.uhz_coin_tips x
       LEFT JOIN public.community_profiles p ON p.user_id=x.recipient_user_id
       WHERE x.donor_user_id=actor ORDER BY x.created_at DESC LIMIT p_limit)t;
 SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.created_at DESC),'[]'::jsonb) INTO received
 FROM (SELECT x.id,x.amount_coins,x.resource_kind,x.resource_id,x.recipient_kind,x.created_at,
       coalesce(p.display_name,'Usuario') AS donor
       FROM private.uhz_coin_tips x
       LEFT JOIN public.community_profiles p ON p.user_id=x.donor_user_id
       WHERE x.recipient_user_id=actor ORDER BY x.created_at DESC LIMIT p_limit)t;
 RETURN jsonb_build_object('ok',true,'sent',sent,'received',received,
   'sent_coins',(SELECT coalesce(sum(amount_coins),0) FROM private.uhz_coin_tips WHERE donor_user_id=actor),
   'received_coins',(SELECT coalesce(sum(amount_coins),0) FROM private.uhz_coin_tips WHERE recipient_user_id=actor));
END $function$;
REVOKE ALL ON FUNCTION public.uhz_coin_tip_my_history(integer) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.uhz_coin_tip_my_history(integer) TO authenticated;
